n, m = 135, 12

print("Whole:", n * m)                                  # 1620
print("By places:", n * 10 + n * 2)                     # 1350 + 270
print("By factors:", (n * 3) * 4)                       # 12 = 3 x 4
print("By parts:", n * 8 + n * 4)                       # 12 = 8 + 4
print("Divided back:", (n * m) // m)                    # 135
